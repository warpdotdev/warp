#[test]
fn for_each_member_limits_zero_usage_rows_to_the_provided_roster() {
    // Regression: the zero-usage roster must come from the current team's
    // members, not every workspace member -- otherwise an admin of
    // multiple teams sees rows for teammates outside the team they're
    // viewing.
    let members = vec![team_member(VIEWER_UID, "viewer@example.com")];

    let rows = MemberUsageRow::for_each_member(&[], &members, SourceFilter::All);

    assert_eq!(
        rows.len(),
        1,
        "expected exactly one row for the sole roster member"
    );
    assert_eq!(rows[0].display_name, "viewer@example.com");
    assert_eq!(rows[0].total_credits, 0);
}

#[test]
fn for_each_member_does_not_synthesize_rows_for_members_outside_the_roster() {
    let members = vec![team_member(VIEWER_UID, "viewer@example.com")];

    let rows = MemberUsageRow::for_each_member(&[], &members, SourceFilter::All);

    assert!(
        !rows.iter().any(|r| r.display_name == "other@example.com"),
        "a member outside the provided roster must not get a zero-usage row"
    );
}
